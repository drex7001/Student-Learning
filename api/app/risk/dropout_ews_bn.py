@dataclass(frozen=True)
class BinaryLogisticCPDSpec:
    """A readable, auditable parameterisation of a binary node's CPD.

    Instead of hand-writing a matrix of ``2 x prod(parent_cards)`` numbers -- which
    nobody can review and any typo silently corrupts -- a binary CPD is declared as an
    additive log-odds model on the probability of the *elevated* (second) state:

    .. math::
        \\mathrm{logit}\\;P(X = \\text{elevated} \\mid \\mathrm{pa}) =
        \\mathrm{logit}(b) + \\sum_{p} \\beta_{p,\\,\\mathrm{state}(p)}
        + \\sum_{\\text{pairs}} \\gamma

    Attributes:
        baseline: probability of the elevated state when *every* parent is in its
            reference (first-listed) state.
        effects: ``{parent: {parent_state: log_odds_increment}}``. Any parent state that
            is omitted contributes ``0.0`` and is therefore a reference level.
        interactions: ``{((parent_a, state_a), (parent_b, state_b)): log_odds_increment}``
            for the departures from additivity that the domain genuinely requires (e.g.
            accommodation buffering neurodivergence).
        clip: floor and ceiling applied to every resulting probability, so that no cell
            is exactly 0 or 1 and no evidence combination can be treated as impossible.
        rationale: one-line justification recorded next to the numbers.
    """

    baseline: float
    effects: Mapping[str, Mapping[str, float]] = field(default_factory=dict)
    interactions: Mapping[tuple[tuple[str, str], tuple[str, str]], float] = field(default_factory=dict)
    clip: tuple[float, float] = (0.02, 0.97)
    rationale: str = ""

    def __post_init__(self) -> None:
        if not 0.0 < self.baseline < 1.0:
            raise ValueError(f"baseline must be strictly inside (0, 1); got {self.baseline}")
        lo, hi = self.clip
        if not 0.0 < lo < hi < 1.0:
            raise ValueError(f"clip must satisfy 0 < lo < hi < 1; got {self.clip}")


@dataclass(frozen=True)
class OrdinalLogisticCPDSpec:
    """Cumulative-logit ("proportional odds") parameterisation of an ordered node.

    Used for the three-state ordered variables. A single latent severity score
    :math:`\\eta(\\mathrm{pa})` is shifted by parent states, and two cutpoints turn it
    into a distribution over ``(low, middle, high)``:

    .. math::
        P(X \\succeq \\text{middle}) = \\sigma(\\eta - c_1), \\quad
        P(X = \\text{high}) = \\sigma(\\eta - c_2), \\quad c_1 < c_2

    This keeps the *ordering* of the states meaningful, which a free 3-row matrix does
    not, and it means one number per parent state has to be defended rather than twelve.

    Attributes:
        cutpoints: ``(c1, c2)`` with ``c1 < c2``.
        effects: ``{parent: {parent_state: latent_score_increment}}``; omitted states are
            reference levels contributing ``0.0``.
        floor: minimum probability given to any state before renormalisation.
        rationale: one-line justification recorded next to the numbers.
    """

    cutpoints: tuple[float, float]
    effects: Mapping[str, Mapping[str, float]] = field(default_factory=dict)
    floor: float = 0.005
    rationale: str = ""

    def __post_init__(self) -> None:
        c1, c2 = self.cutpoints
        if not c1 < c2:
            raise ValueError(f"cutpoints must be increasing; got {self.cutpoints}")
        if not 0.0 <= self.floor < 0.1:
            raise ValueError(f"floor must be in [0, 0.1); got {self.floor}")


def _logit(p: float) -> float:
    return float(np.log(p / (1.0 - p)))


def _sigmoid(x: float) -> float:
    return float(1.0 / (1.0 + np.exp(-x)))


def _parent_state_combinations(parents: Sequence[str]) -> list[tuple[str, ...]]:
    """Parent-state tuples in pgmpy's CPD *column* order.

    pgmpy lays columns out as ``itertools.product`` over the evidence list, i.e. the
    **last** evidence variable varies fastest. ``test_cpd_cell_alignment`` verifies this
    empirically against ``TabularCPD.get_value`` rather than trusting the convention.
    """
    return list(itertools.product(*(NODE_STATES[p] for p in parents)))


def make_binary_cpd(
    variable: str,
    parents: Sequence[str],
    spec: BinaryLogisticCPDSpec,
) -> TabularCPD:
    """Construct a :class:`TabularCPD` for a two-state node from a logistic spec.

    Args:
        variable: node name; must be binary in :data:`NODE_STATES`.
        parents: parent node names, in the order used for ``evidence``.
        spec: the additive log-odds parameterisation.

    Returns:
        A ``TabularCPD`` with explicit ``state_names`` and columns summing to 1.

    Raises:
        ValueError: if the node is not binary, or the spec names an unknown parent or
            parent state.
    """
    states = NODE_STATES[variable]
    if len(states) != 2:
        raise ValueError(f"{variable} has {len(states)} states; make_binary_cpd requires 2")

    _validate_effect_keys(variable, parents, spec.effects)
    _validate_interaction_keys(variable, parents, spec.interactions)

    base_logit = _logit(spec.baseline)
    lo, hi = spec.clip
    elevated_probs: list[float] = []
    for combo in _parent_state_combinations(parents):
        assignment = dict(zip(parents, combo))
        score = base_logit
        for parent, state in assignment.items():
            score += spec.effects.get(parent, {}).get(state, 0.0)
        for (pa, sa), (pb, sb) in spec.interactions:
            if assignment.get(pa) == sa and assignment.get(pb) == sb:
                score += spec.interactions[((pa, sa), (pb, sb))]
        elevated_probs.append(min(max(_sigmoid(score), lo), hi))

    elevated = np.asarray(elevated_probs, dtype=float)
    values = np.vstack([1.0 - elevated, elevated])  # row 0 = reference state
    return _tabular_cpd(variable, parents, values)


def make_ordinal_cpd(
    variable: str,
    parents: Sequence[str],
    spec: OrdinalLogisticCPDSpec,
) -> TabularCPD:
    """Construct a :class:`TabularCPD` for an ordered three-state node.

    Args:
        variable: node name; must have exactly 3 ordered states in :data:`NODE_STATES`.
        parents: parent node names, in the order used for ``evidence``.
        spec: the cumulative-logit parameterisation.

    Returns:
        A ``TabularCPD`` with explicit ``state_names`` and columns summing to 1.

    Raises:
        ValueError: if the node does not have 3 states, or the spec names an unknown
            parent or parent state.
    """
    states = NODE_STATES[variable]
    if len(states) != 3:
        raise ValueError(f"{variable} has {len(states)} states; make_ordinal_cpd requires 3")

    _validate_effect_keys(variable, parents, spec.effects)
    c1, c2 = spec.cutpoints

    columns: list[np.ndarray] = []
    for combo in _parent_state_combinations(parents):
        eta = 0.0
        for parent, state in zip(parents, combo):
            eta += spec.effects.get(parent, {}).get(state, 0.0)
        p_at_least_mid = _sigmoid(eta - c1)
        p_high = _sigmoid(eta - c2)
        column = np.array([1.0 - p_at_least_mid, p_at_least_mid - p_high, p_high], dtype=float)
        column = np.clip(column, spec.floor, None)
        columns.append(column / column.sum())

    return _tabular_cpd(variable, parents, np.column_stack(columns))


def make_prior_cpd(variable: str, probabilities: Sequence[float]) -> TabularCPD:
    """Construct a marginal (root) CPD from an explicit probability vector.

    Args:
        variable: root node name.
        probabilities: one probability per state, in :data:`NODE_STATES` order.

    Raises:
        ValueError: on length mismatch, non-positive entries, or a vector that does not
            sum to 1 within :data:`PROBABILITY_TOLERANCE`.
    """
    states = NODE_STATES[variable]
    if len(probabilities) != len(states):
        raise ValueError(f"{variable}: expected {len(states)} probabilities, got {len(probabilities)}")
    vector = np.asarray(probabilities, dtype=float)
    if np.any(vector <= 0.0):
        raise ValueError(f"{variable}: priors must be strictly positive, got {probabilities}")
    if abs(vector.sum() - 1.0) > 1e-8:
        raise ValueError(f"{variable}: priors sum to {vector.sum():.10f}, not 1.0")
    return _tabular_cpd(variable, (), vector.reshape(-1, 1))


def _tabular_cpd(variable: str, parents: Sequence[str], values: np.ndarray) -> TabularCPD:
    """Assemble a ``TabularCPD`` with explicit state names and a renormalised matrix."""
    values = np.asarray(values, dtype=float)
    values = values / values.sum(axis=0, keepdims=True)  # guard against clip-induced drift
    state_names = {variable: list(NODE_STATES[variable])}
    state_names.update({p: list(NODE_STATES[p]) for p in parents})
    return TabularCPD(
        variable=variable,
        variable_card=len(NODE_STATES[variable]),
        values=values,
        evidence=list(parents) or None,
        evidence_card=[len(NODE_STATES[p]) for p in parents] or None,
        state_names=state_names,
    )


def _validate_effect_keys(
    variable: str, parents: Sequence[str], effects: Mapping[str, Mapping[str, float]]
) -> None:
    for parent, by_state in effects.items():
        if parent not in parents:
            raise ValueError(f"{variable}: effect declared for non-parent '{parent}'")
        unknown = set(by_state) - set(NODE_STATES[parent])
        if unknown:
            raise ValueError(f"{variable}: unknown states for parent '{parent}': {sorted(unknown)}")


def _validate_interaction_keys(
    variable: str,
    parents: Sequence[str],
    interactions: Mapping[tuple[tuple[str, str], tuple[str, str]], float],
) -> None:
    for pair in interactions:
        for parent, state in pair:
            if parent not in parents:
                raise ValueError(f"{variable}: interaction declared for non-parent '{parent}'")
            if state not in NODE_STATES[parent]:
                raise ValueError(f"{variable}: interaction uses unknown state '{parent}={state}'")



def build_structure(variant: ModelVariant = ModelVariant.BASELINE) -> DiscreteBayesianNetwork:
    """Build the DAG (structure only, no parameters).

    Args:
        variant: which structural hypothesis to instantiate.

    Returns:
        A parameterless :class:`DiscreteBayesianNetwork` whose nodes are exactly the keys
        of :data:`NODE_STATES`.

    Raises:
        ValueError: if the edge list references an unregistered node, if the graph is
            cyclic, or if a protected/immutable characteristic is a direct parent of the
            outcome.
    """
    edges = list(BASELINE_EDGES)
    if variant is ModelVariant.AMENDED:
        edges += list(AMENDMENT_EDGES)

    unknown = {n for edge in edges for n in edge} - set(NODE_STATES)
    if unknown:
        raise ValueError(f"Edges reference nodes missing from NODE_STATES: {sorted(unknown)}")

    # Check acyclicity on a plain DiGraph *before* handing the edges to pgmpy. pgmpy's
    # constructor also rejects cycles, but reports them as an opaque networkx
    # "Input is not a valid edge list"; validating first lets the error name the cycle.
    scaffold = nx.DiGraph()
    scaffold.add_nodes_from(NODE_STATES)
    scaffold.add_edges_from(edges)
    _assert_acyclic(scaffold)

    model = DiscreteBayesianNetwork(edges)
    model.add_nodes_from(NODE_STATES)  # keep isolated nodes, if any, in the model

    _assert_acyclic(model)  # post-condition: pgmpy did not reinterpret the edge list
    _assert_no_protected_shortcut(model)
    LOGGER.info(
        "Structure '%s' built: %d nodes, %d edges", variant.value, len(model.nodes()), len(model.edges())
    )
    return model


def _assert_acyclic(graph: Any) -> None:
    """Fail loudly if the structure is not a DAG, naming the offending cycle.

    Being a DAG is a *necessary* condition for the factorisation to be well defined. It
    is emphatically **not** sufficient for the graph to be causally correct -- an
    arbitrary acyclic ordering of variables is still a DAG.
    """
    if not nx.is_directed_acyclic_graph(graph):
        cycle = nx.find_cycle(graph, orientation="original")
        raise ValueError(
            f"Structure contains a directed cycle: "
            f"{' -> '.join(str(edge[0]) for edge in cycle)} -> {cycle[0][0]}"
        )


def _assert_no_protected_shortcut(model: DiscreteBayesianNetwork) -> None:
    """Enforce the fairness constraint that protected characteristics act only via
    mediating mechanisms, never as direct parents of the outcome."""
    offending = PROTECTED_OR_IMMUTABLE_NODES.intersection(model.get_parents(TARGET_NODE))
    # Grade_Band -> outcome is required by the brief and is defended in REPORT.md as a
    # *structural-transition* variable (grade 5 / O-Level junctures), not a personal trait.
    offending -= {"Grade_Band"}
    if offending:
        raise ValueError(
            f"Protected/immutable characteristics must not be direct parents of "
            f"{TARGET_NODE}: {sorted(offending)}"
        )



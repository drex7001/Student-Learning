@dataclass(frozen=True)
class RiskModel:
    """An immutable, reusable bundle: DAG + parameters + a warm inference engine.

    Build this **once** (e.g. in a FastAPI lifespan handler) and share it. It holds no
    mutable state, so it is safe to reuse across requests; ``VariableElimination`` is
    constructed eagerly because that is the expensive part.
    """

    model: DiscreteBayesianNetwork
    variant: ModelVariant
    engine: VariableElimination
    fingerprint: str
    causal_engine: Any = None
    provenance: str = PRIOR_PROVENANCE

    @property
    def nodes(self) -> tuple[str, ...]:
        return tuple(NODE_STATES)

    def states_of(self, node: str) -> tuple[str, ...]:
        if node not in NODE_STATES:
            raise UnknownNodeError(f"Unknown variable '{node}'")
        return NODE_STATES[node]


def build_model(variant: ModelVariant = ModelVariant.BASELINE) -> RiskModel:
    """Build, parameterise and validate a complete model bundle.

    Args:
        variant: which structural hypothesis to build.

    Returns:
        A ready-to-query :class:`RiskModel`.

    Raises:
        ValueError: if CPD validation fails or ``pgmpy``'s ``check_model`` rejects the
            network (missing CPD, cardinality mismatch, unnormalised column).
    """
    model = build_structure(variant)
    cpds = build_cpds(variant)
    validate_cpds(cpds)
    model.add_cpds(*cpds)

    missing = [n for n in model.nodes() if model.get_cpds(n) is None]
    if missing:
        raise ValueError(f"Nodes without a CPD: {sorted(missing)}")
    if not model.check_model():  # pragma: no cover - pgmpy raises rather than returns False
        raise ValueError("pgmpy check_model() rejected the network")

    LOGGER.info("check_model() = True for variant '%s'", variant.value)
    return RiskModel(
        model=model,
        variant=variant,
        engine=VariableElimination(model),
        fingerprint=model_fingerprint(model, variant),
        causal_engine=CausalInference(model) if _HAS_CAUSAL_INFERENCE else None,
    )


def model_fingerprint(model: DiscreteBayesianNetwork, variant: ModelVariant) -> str:
    """Return a short content hash over structure + parameters.

    Every inference result carries this so an audit log can prove *which* parameter set
    produced a given number. Changing one probability changes the fingerprint.
    """
    hasher = hashlib.sha256()
    hasher.update(variant.value.encode())
    for edge in sorted(model.edges()):
        hasher.update("->".join(edge).encode())
    for cpd in sorted(model.get_cpds(), key=lambda c: str(c.variable)):
        hasher.update(str(cpd.variable).encode())
        # Include the parent order and state names: identical value matrices under a
        # different column layout mean a different model, and must not collide.
        for name in cpd.variables:
            hasher.update(f"|{name}:{','.join(map(str, cpd.state_names[name]))}".encode())
        hasher.update(np.ascontiguousarray(cpd.get_values(), dtype=np.float64).tobytes())
    return hasher.hexdigest()[:16]


def describe_structure(risk_model: RiskModel) -> dict[str, Any]:
    """Return a serialisable description of the DAG: edges, parents, roots, orphan check."""
    model = risk_model.model
    parents = {node: sorted(model.get_parents(node)) for node in NODE_STATES}
    return {
        "variant": risk_model.variant.value,
        "fingerprint": risk_model.fingerprint,
        "n_nodes": len(model.nodes()),
        "n_edges": len(model.edges()),
        "edges": sorted("->".join(e) for e in model.edges()),
        "parents": parents,
        "root_nodes": sorted(n for n, ps in parents.items() if not ps),
        "target": TARGET_NODE,
        "target_parents": parents[TARGET_NODE],
        "max_parent_count": max(len(ps) for ps in parents.values()),
        "max_cpd_columns": max(
            int(np.prod([len(NODE_STATES[p]) for p in ps])) if ps else 1 for ps in parents.values()
        ),
        "provenance": risk_model.provenance,
    }



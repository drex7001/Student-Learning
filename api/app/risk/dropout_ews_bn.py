def summarise_evidence_levels(
    variant: ModelVariant = ModelVariant.BASELINE,
) -> dict[str, Any]:
    """Group a variant's edges by evidence level, for the report and for auditing.

    Returns:
        A serialisable dict with counts and the edge list per level, plus the share of
        edges that are still unvalidated expert hypotheses -- the honest headline number
        for how much of the model rests on assumption.

    Raises:
        KeyError: if an edge has no recorded evidence level.
    """
    edges = list(BASELINE_EDGES)
    if variant is ModelVariant.AMENDED:
        edges += list(AMENDMENT_EDGES)
    grouped: dict[str, list[str]] = {level.value: [] for level in EvidenceLevel}
    for edge in edges:
        grouped[EDGE_EVIDENCE[edge].value].append("->".join(edge))
    return {
        "variant": variant.value,
        "n_edges": len(edges),
        "counts": {level: len(items) for level, items in grouped.items()},
        "edges_by_level": {level: sorted(items) for level, items in grouped.items()},
        "expert_hypothesis_share": round(
            len(grouped[EvidenceLevel.EXPERT_HYPOTHESIS.value]) / len(edges), 4
        ),
    }



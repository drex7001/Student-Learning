def build_cpds(variant: ModelVariant = ModelVariant.BASELINE) -> list[TabularCPD]:
    """Build one CPD per node, from the declarative specs above.

    Args:
        variant: which structural hypothesis the CPDs must match.

    Returns:
        A list of ``TabularCPD`` objects, one per node in :data:`NODE_STATES`.

    Raises:
        ValueError: if a node has neither a prior, a binary spec nor an ordinal spec for
            the requested variant, or if a spec's parents disagree with the structure.
    """
    structure = build_structure(variant)
    binary_specs = dict(_BINARY_SPECS)
    ordinal_specs = dict(_ORDINAL_SPECS)
    root_priors = dict(_ROOT_PRIORS)

    if variant is ModelVariant.AMENDED:
        binary_specs.update(_AMENDED_BINARY_SPECS)
        ordinal_specs.update(_AMENDED_ORDINAL_SPECS)
        # These nodes stop being roots under the amendment.
        for promoted in ("Economic_Strain", "School_Accommodation", "Bullying_Social_Exclusion"):
            root_priors.pop(promoted, None)

    cpds: list[TabularCPD] = []
    for node in NODE_STATES:
        parents = tuple(sorted(structure.get_parents(node)))
        if node in ordinal_specs:
            cpds.append(make_ordinal_cpd(node, parents, ordinal_specs[node]))
        elif node in binary_specs:
            cpds.append(make_binary_cpd(node, parents, binary_specs[node]))
        elif node in root_priors:
            if parents:
                raise ValueError(f"{node} has parents {parents} but is declared as a root prior")
            cpds.append(make_prior_cpd(node, root_priors[node]))
        else:
            raise ValueError(f"No CPD specification found for node '{node}' in variant '{variant.value}'")
    LOGGER.info("Built %d CPDs for variant '%s'", len(cpds), variant.value)
    return cpds


def validate_cpds(cpds: Iterable[TabularCPD], *, forbid_deterministic: bool = True) -> None:
    """Check the arithmetic and the safety properties of a CPD collection.

    Verifies, for every CPD: finite values, every entry inside ``[0, 1]``, every
    conditional column summing to ``1`` within :data:`PROBABILITY_TOLERANCE`, and -- unless
    ``forbid_deterministic`` is turned off -- no entry that is *exactly* 0 or 1.

    The last check matters ethically, not just numerically. A zero says "this combination
    of circumstances is impossible", and no elicited prior about children's lives earns
    that. It also makes the model brittle: a single zero can make otherwise informative
    evidence unusable.

    Raises:
        ValueError: with the offending variable and column named, on the first failure.
    """
    for cpd in cpds:
        matrix = np.asarray(cpd.get_values(), dtype=float)
        if not np.all(np.isfinite(matrix)):
            raise ValueError(f"CPD for {cpd.variable} contains non-finite entries")
        if np.any(matrix < 0.0) or np.any(matrix > 1.0):
            raise ValueError(f"CPD for {cpd.variable} has entries outside [0, 1]")
        if forbid_deterministic and (np.any(matrix <= 0.0) or np.any(matrix >= 1.0)):
            raise ValueError(
                f"CPD for {cpd.variable} contains a deterministic 0 or 1; elicited priors "
                f"must not declare any circumstance impossible or certain"
            )
        sums = matrix.sum(axis=0)
        bad = np.nonzero(np.abs(sums - 1.0) > PROBABILITY_TOLERANCE)[0]
        if bad.size:
            raise ValueError(
                f"CPD for {cpd.variable}: column(s) {bad.tolist()} sum to "
                f"{sums[bad].tolist()} instead of 1.0"
            )
    LOGGER.info("validate_cpds: all columns normalised, in range, and non-deterministic")



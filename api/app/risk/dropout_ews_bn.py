# 7. Interventions  (Part 6: observational vs interventional)
# ---------------------------------------------------------------------------


def estimate_intervention_effect(
    risk_model: RiskModel,
    intervention: Mapping[str, str],
    evidence: Mapping[str, str] | None = None,
    *,
    target: str = TARGET_NODE,
    label: str | None = None,
) -> dict[str, Any]:
    """Interventional distribution ``P(target | do(intervention), evidence)``.

    Computed by **truncated factorisation on the mutilated graph**: every edge into an
    intervened variable is cut, which removes exactly the back-door (confounding) paths
    that make the observational conditional a biased estimate of the effect of acting.
    Once the intervened variable is a root of the mutilated graph, conditioning on its
    assigned state there *is* the do-distribution, and the variable's own (now irrelevant)
    marginal cancels in the normalisation. :func:`validate_cpds` guarantees every CPD
    entry is strictly positive, so that normalisation is always well defined.

    .. warning::
        ``pgmpy.inference.CausalInference.query`` is **not** used as the primary engine.
        In pgmpy 1.1.2, whenever the intervened variable has parents, it silently ignores
        ``evidence`` variables outside the back-door adjustment set it selects. On this
        network ``query(do={"Transport_Burden": "Low"},
        evidence={"Previous_Attendance": "Irregular"})`` returns P(High)=0.1265 -- the
        value for *no* evidence -- where the correct answer is 0.2465, an error of nearly
        a factor of two. pgmpy is therefore run only as a cross-check in the no-evidence
        case, where the two agree exactly. See :func:`audit_pgmpy_causal_api`.

    Args:
        risk_model: a bundle from :func:`build_model`.
        intervention: ``{variable: state}`` to set by fiat. Every variable must be in
            :data:`MODIFIABLE_NODES`.
        evidence: additional passive observations to condition on.
        target: variable to query.
        label: optional human-readable tag echoed back.

    Returns:
        A serialisable dict shaped like :func:`infer_dropout_risk`, with
        ``interpretation="interventional_do"``, plus ``intervention``, the
        ``mutilated_edges_removed`` count, the ``method`` used, and a
        ``pgmpy_cross_check`` block recording whether the library agrees.

    Raises:
        NonModifiableInterventionError: if any target is not on the modifiable allowlist.
            This is a deliberate ethical guardrail: the model must never be asked what
            would happen "if this child were not autistic".
        EvidenceError: on malformed intervention/evidence variables or states.
    """
    if not intervention:
        raise EvidenceError("intervention must name at least one variable")

    illegal = sorted(set(intervention) - MODIFIABLE_NODES)
    if illegal:
        raise NonModifiableInterventionError(
            f"Refusing to intervene on non-modifiable variable(s) {illegal}. "
            f"do() is restricted to modifiable school/household factors: "
            f"{sorted(MODIFIABLE_NODES)}. Immutable or protected characteristics such as "
            f"{sorted(PROTECTED_OR_IMMUTABLE_NODES)} are never valid intervention targets."
        )

    do_states = validate_evidence(intervention, target=target)
    obs_states = validate_evidence(evidence or {}, target=target)
    overlap = sorted(set(do_states) & set(obs_states))
    if overlap:
        raise EvidenceError(f"Variable(s) {overlap} appear as both intervention and evidence")

    removed = sum(len(risk_model.model.get_parents(v)) for v in do_states)

    # Primary, verified path: truncated factorisation on the mutilated graph.
    method = "mutilated graph (model.do) + conditioning [truncated factorisation]"
    mutilated = risk_model.model.do(list(do_states))
    factor = VariableElimination(mutilated).query(
        variables=[target],
        evidence={**do_states, **obs_states},
        show_progress=False,
    )
    posterior = _factor_to_dict(factor, target)

    # Cross-check against the library, but only where the library is trustworthy.
    cross_check: dict[str, Any] = {"performed": False, "reason": "pgmpy CausalInference unavailable"}
    if _HAS_CAUSAL_INFERENCE and not obs_states:
        causal = risk_model.causal_engine or CausalInference(risk_model.model)
        library = _factor_to_dict(
            causal.query(variables=[target], do=dict(do_states), show_progress=False), target
        )
        gap = max(abs(library[s] - posterior[s]) for s in posterior)
        cross_check = {
            "performed": True,
            "engine": "pgmpy.CausalInference.query(do=...)",
            "posterior": library,
            "max_abs_difference": round(gap, 9),
            "agrees": gap < 1e-6,
        }
        if gap >= 1e-6:  # pragma: no cover - would indicate a library regression
            LOGGER.warning(
                "pgmpy CausalInference disagrees with truncated factorisation by %.2e for "
                "do(%s); trusting the mutilated-graph result",
                gap,
                do_states,
            )
    elif _HAS_CAUSAL_INFERENCE:
        cross_check = {
            "performed": False,
            "reason": (
                "skipped deliberately: pgmpy 1.1.2 CausalInference.query ignores evidence "
                "variables outside its chosen back-door adjustment set, so it cannot be "
                "used to check a conditional interventional query"
            ),
        }

    top = max(posterior, key=posterior.__getitem__)
    return {
        "label": label,
        "target": target,
        "interpretation": "interventional_do",
        "method": method,
        "posterior": posterior,
        "highest_state": top,
        "highest_probability": posterior[top],
        "intervention": do_states,
        "evidence": obs_states,
        "mutilated_edges_removed": removed,
        "pgmpy_cross_check": cross_check,
        "model_variant": risk_model.variant.value,
        "model_fingerprint": risk_model.fingerprint,
        "computed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "provenance": risk_model.provenance,
        "caveat": (
            "An interventional estimate is only as good as the DAG. It assumes no "
            "unmeasured common cause of the intervened variable and the outcome."
        ),
    }


def compare_observational_and_interventional(
    risk_model: RiskModel,
    variable: str,
    state: str,
    *,
    evidence: Mapping[str, str] | None = None,
    target: str = TARGET_NODE,
) -> dict[str, Any]:
    """Put ``P(Y | X = x)`` and ``P(Y | do(X = x))`` side by side for one variable.

    Returns a dict containing both posteriors, their per-state difference, the maximum
    absolute gap, whether the two coincide, and *why*: if ``variable`` has no parents in
    this DAG there is no back-door path to block, so the two are algebraically identical
    and the distinction -- though conceptually crucial -- is empty **as modelled**.
    """
    obs = infer_dropout_risk(risk_model, {**(evidence or {}), variable: state}, target=target)
    do = estimate_intervention_effect(
        risk_model, {variable: state}, evidence=evidence, target=target
    )
    diff = {s: round(do["posterior"][s] - obs["posterior"][s], 6) for s in NODE_STATES[target]}
    parents = sorted(risk_model.model.get_parents(variable))
    return {
        "variable": variable,
        "state": state,
        "conditioning_evidence": dict(evidence or {}),
        "observational": obs["posterior"],
        "interventional": do["posterior"],
        "difference_do_minus_obs": diff,
        "max_abs_difference": round(max(abs(v) for v in diff.values()), 6),
        "identical_in_this_dag": max(abs(v) for v in diff.values()) < 1e-6,
        "parents_of_variable": parents,
        "explanation": (
            f"'{variable}' has no parents in this DAG, so no back-door path exists and "
            f"the mutilated graph equals the original. The two quantities coincide *as a "
            f"consequence of the assumed structure*, not as a general fact -- in reality "
            f"schools do not assign this variable at random."
            if not parents
            else f"'{variable}' has parents {parents}, so conditioning on it also carries "
            f"information back up those edges. do() cuts them, which is why the two "
            f"quantities differ here."
        ),
    }



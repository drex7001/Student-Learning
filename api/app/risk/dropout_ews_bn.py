def validate_evidence(evidence: Mapping[str, str], *, target: str = TARGET_NODE) -> dict[str, str]:
    """Normalise and strictly validate an evidence mapping.

    Args:
        evidence: ``{variable: state}``; may be empty.
        target: the query variable, which must be a known node and must not also appear as
            evidence.

    Returns:
        A plain ``dict`` copy of the evidence.

    Raises:
        UnknownNodeError: on a variable outside :data:`NODE_STATES`, on an unknown
            ``target``, or on evidence that fixes the query target.
        UnknownStateError: on a state the variable does not have (the message lists the
            legal states, so an API client can correct itself).
    """
    if target not in NODE_STATES:
        # Without this, a bad target reaches pgmpy and surfaces as a raw NetworkXError,
        # which a service layer would turn into a 500 instead of a 422.
        raise UnknownNodeError(
            f"Unknown query target '{target}'. Known variables: {sorted(NODE_STATES)}"
        )
    validated: dict[str, str] = {}
    for node, state in dict(evidence).items():
        if node not in NODE_STATES:
            raise UnknownNodeError(
                f"Unknown variable '{node}'. Known variables: {sorted(NODE_STATES)}"
            )
        if node == target:
            raise UnknownNodeError(f"Cannot supply the query target '{target}' as evidence")
        if state not in NODE_STATES[node]:
            raise UnknownStateError(
                f"Unknown state '{state}' for variable '{node}'. "
                f"Valid states: {list(NODE_STATES[node])}"
            )
        validated[node] = state
    return validated


def infer_dropout_risk(
    risk_model: RiskModel,
    evidence: Mapping[str, str] | None = None,
    *,
    target: str = TARGET_NODE,
    label: str | None = None,
) -> dict[str, Any]:
    """Observational posterior over ``target`` given ``evidence``.

    This is the function a FastAPI route should call. It takes only JSON-native inputs,
    returns only JSON-native outputs, mutates nothing, and raises
    :class:`EvidenceError` subclasses that map cleanly onto HTTP 422.

    Args:
        risk_model: a bundle from :func:`build_model`.
        evidence: ``{variable: state}`` observations; ``None`` yields the prior.
        target: variable to query.
        label: optional human-readable tag echoed back (useful for scenario tables).

    Returns:
        A serialisable dict with ``posterior`` (state -> probability), ``highest_state``,
        ``highest_probability``, the ``evidence`` used, the model ``fingerprint`` and
        ``variant``, a UTC ``computed_at`` timestamp, the ``interpretation`` kind, and the
        mandatory ``provenance`` and ``caveat`` strings.

    Raises:
        UnknownNodeError, UnknownStateError: see :func:`validate_evidence`.
    """
    used = validate_evidence(evidence or {}, target=target)
    factor = risk_model.engine.query(variables=[target], evidence=used or None, show_progress=False)
    posterior = _factor_to_dict(factor, target)
    top = max(posterior, key=posterior.__getitem__)
    return {
        "label": label,
        "target": target,
        "interpretation": "observational_conditional",
        "posterior": posterior,
        "highest_state": top,
        "highest_probability": posterior[top],
        "evidence": used,
        "n_evidence": len(used),
        "model_variant": risk_model.variant.value,
        "model_fingerprint": risk_model.fingerprint,
        "computed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "provenance": risk_model.provenance,
        "caveat": (
            "Decision-support only. Not a diagnosis, not a prediction about this "
            "individual, and not a basis for any automated action. Requires human review."
        ),
    }


def _factor_to_dict(factor: Any, variable: str) -> dict[str, float]:
    """Convert a pgmpy ``DiscreteFactor`` over one variable into ``{state: probability}``."""
    names = list(factor.state_names[variable])
    values = np.asarray(factor.values, dtype=float).ravel()
    total = float(values.sum())
    return {name: round(float(v) / total, 6) for name, v in zip(names, values)}



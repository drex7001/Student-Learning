"""Bayesian-network prototype for a school-disengagement *early-support* screen.

Purpose
-------
This module builds a **static two-period discrete Bayesian network** that estimates a
distribution over next-term disengagement/dropout risk categories for a student, given
household, school-environment and prior-term evidence, in the Sri Lankan school context.

What this is NOT
----------------
*   It is **not** a diagnostic instrument. It diagnoses nothing about any child.
*   It is **not** a disciplinary tool and must never be used to exclude, stream, punish,
    rank, or permanently label a student, a family, a teacher, or a school.
*   It is **not** an automated decision system. Every output is a *conversation starter*
    for a human review team (class teacher, counsellor, special-education professional,
    social-service officer, and the family/student themselves).
*   The numbers in :func:`build_cpds` are **illustrative expert-elicited priors for
    software testing; not validated Sri Lankan prevalence estimates.** They are here so
    the software can be exercised end to end. They must be replaced by calibrated
    parameters before any output is shown to any real person.

Design commitments encoded in the structure
-------------------------------------------
1.  ``Neuro_Type`` has **no** direct edge to the outcome. Risk for a neurodivergent
    student arises only through *environmental mismatch*, *exclusion*, *distress* and
    *insufficient accommodation* -- all of which are modifiable by the school.
2.  Background/protected-adjacent characteristics (``Sector``, ``Grade_Band``,
    ``Parent_Education`` ...) act through explicit resource and barrier mechanisms rather
    than as direct causes of dropout.
3.  Temporal ordering is enforced by ``Previous_*`` / ``Current_*`` / ``Next_Term_*``
    prefixes, so no same-period feedback cycles are created.
4.  Interventions (``do``) are permitted **only** on an allowlist of modifiable factors
    (:data:`MODIFIABLE_NODES`). Intervening on ``Neuro_Type`` or on any other immutable
    or protected characteristic raises :class:`NonModifiableInterventionError`.

Requires: pgmpy >= 1.0 (developed against 1.1.2), pandas, numpy.

Run
---
    python dropout_ews_bn.py --out-dir outputs

Author's note: read ``REPORT.md`` next to this file before interpreting any number.
"""


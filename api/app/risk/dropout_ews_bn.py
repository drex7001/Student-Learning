def perturb_cpd(cpd: TabularCPD, target: SensitivityTarget, factor: float) -> TabularCPD:
    """Return a copy of ``cpd`` with one state's probability scaled in matching columns.

    Each matching column has ``P(variable = target.state)`` multiplied by ``factor``,
    is clipped away from 0 and 1, and is then renormalised so the column still sums to 1
    (the residual mass is redistributed proportionally across the other states).

    Raises:
        ValueError: if ``factor <= 0``, or if ``parent_filter`` matches no column, which
            would silently produce a no-op "sensitivity" result.
    """
    if factor <= 0.0:
        raise ValueError(f"factor must be positive; got {factor}")

    parents = list(cpd.variables[1:])
    unknown = set(target.parent_filter) - set(parents)
    if unknown:
        raise ValueError(
            f"parent_filter for {target.variable} names non-parents {sorted(unknown)}; "
            f"actual parents are {parents}"
        )

    values = np.array(cpd.get_values(), dtype=float)
    row = list(NODE_STATES[target.variable]).index(target.state)
    combos = _parent_state_combinations(parents)
    matched = 0
    for col, combo in enumerate(combos):
        assignment = dict(zip(parents, combo))
        if any(assignment.get(p) != s for p, s in target.parent_filter.items()):
            continue
        matched += 1
        column = values[:, col]
        others = np.delete(np.arange(len(column)), row)
        new_p = float(np.clip(column[row] * factor, 1e-4, 1.0 - 1e-4))
        remaining = column[others]
        column[row] = new_p
        column[others] = (
            remaining / remaining.sum() * (1.0 - new_p)
            if remaining.sum() > 0
            else (1.0 - new_p) / len(others)
        )
        values[:, col] = column

    if matched == 0:
        raise ValueError(
            f"parent_filter {dict(target.parent_filter)} matched no column of "
            f"{target.variable}; the perturbation would be a no-op"
        )
    return _tabular_cpd(target.variable, parents, values)


def build_perturbed_model(
    variant: ModelVariant, target: SensitivityTarget, factor: float
) -> RiskModel:
    """Rebuild a complete model with exactly one parameter group perturbed."""
    model = build_structure(variant)
    cpds = []
    for cpd in build_cpds(variant):
        cpds.append(perturb_cpd(cpd, target, factor) if cpd.variable == target.variable else cpd)
    validate_cpds(cpds)
    model.add_cpds(*cpds)
    if not model.check_model():  # pragma: no cover
        raise ValueError("perturbed model failed check_model()")
    return RiskModel(
        model=model,
        variant=variant,
        engine=VariableElimination(model),
        fingerprint=model_fingerprint(model, variant),
    )


def run_sensitivity_analysis(
    risk_model: RiskModel,
    *,
    targets: Sequence[SensitivityTarget] = SENSITIVITY_TARGETS,
    deltas: Sequence[float] = (-0.10, 0.10),
    scenarios: Sequence[tuple[str, str, dict[str, str], str]] = SCENARIOS,
) -> dict[str, Any]:
    """One-at-a-time +/-10% sensitivity analysis on the scenario battery.

    For each target parameter group and each relative perturbation, the model is rebuilt
    and the whole scenario battery re-run. The report states whether the **ranking** of
    scenarios by ``P(High)`` is preserved -- which is the property that actually matters
    for a triage tool, far more than whether individual probabilities move.

    Returns:
        A serialisable dict with the baseline ranking, one record per (target, delta),
        the maximum absolute shift in ``P(High)``, whether any ranking flipped, and an
        explicit statement of this method's limitations.
    """
    base = compare_scenarios(risk_model, scenarios)
    base_rank = base["ranking_by_p_high_descending"]
    base_p_high = {r["label"]: r["posterior"]["High"] for r in base["results"]}

    records: list[dict[str, Any]] = []
    for target in targets:
        for delta in deltas:
            factor = 1.0 + delta
            perturbed = build_perturbed_model(risk_model.variant, target, factor)
            run = compare_scenarios(perturbed, scenarios)
            p_high = {r["label"]: r["posterior"]["High"] for r in run["results"]}
            shifts = {k: round(p_high[k] - base_p_high[k], 6) for k in base_p_high}
            worst = max(shifts, key=lambda k: abs(shifts[k]))
            records.append(
                {
                    "target": target.name,
                    "perturbed_parameter": (
                        f"P({target.variable}={target.state} | "
                        f"{', '.join(f'{k}={v}' for k, v in target.parent_filter.items()) or 'any'})"
                    ),
                    "question": target.question,
                    "relative_delta": delta,
                    "ranking": run["ranking_by_p_high_descending"],
                    "ranking_preserved": run["ranking_by_p_high_descending"] == base_rank,
                    "p_high_shift_by_scenario": shifts,
                    "max_abs_shift": round(abs(shifts[worst]), 6),
                    "most_affected_scenario": worst,
                }
            )
            LOGGER.info(
                "sensitivity %-38s delta=%+.0f%%  max|dP(High)|=%.4f  ranking_preserved=%s",
                target.name,
                delta * 100,
                abs(shifts[worst]),
                run["ranking_by_p_high_descending"] == base_rank,
            )

    unstable = [r for r in records if not r["ranking_preserved"]]
    return {
        "model_variant": risk_model.variant.value,
        "baseline_ranking": base_rank,
        "baseline_p_high": base_p_high,
        "records": records,
        "n_perturbations": len(records),
        "n_rank_changes": len(unstable),
        "all_rankings_preserved": not unstable,
        "largest_max_abs_shift": max((r["max_abs_shift"] for r in records), default=0.0),
        "limitations": [
            "One-at-a-time perturbation of a single parameter group is the weakest form "
            "of sensitivity analysis. It cannot detect compensating or interacting "
            "misspecification; joint perturbation and full sensitivity functions "
            "(Chan & Darwiche style) are required before any deployment claim.",
            "Rank stability under +/-10% is necessary, not sufficient. The structure "
            "itself -- which edges exist at all -- dominates parameter uncertainty here.",
            "The +/-10% band is arbitrary and is not an elicited credible interval. Real "
            "expert uncertainty on several of these parameters is far wider.",
        ],
    }



#: The variables a Sri Lankan school plausibly already holds at screening time: the
#: attendance register, a term result, and the grade. Deliberately minimal -- see the
#: data-minimisation argument in REPORT.md section 11.
OBSERVABLE_AT_SCREENING: Final[tuple[str, ...]] = (
    "Previous_Attendance",
    "Current_Attendance",
    "School_Engagement",
    "Grade_Band",
)


def estimate_screening_burden(
    risk_model: RiskModel,
    frame: pd.DataFrame,
    *,
    thresholds: Sequence[float] = (0.20, 0.35, 0.50, 0.65),
    observables: Sequence[str] = OBSERVABLE_AT_SCREENING,
    illustrative_true_rates: Sequence[float] = (0.01, 0.02, 0.05),
    target: str = TARGET_NODE,
) -> dict[str, Any]:
    """Quantify how many students a P(High) threshold would send to human review.

    This is the arithmetic that decides whether an early-warning system is usable or
    merely stressful. It is computed by scoring each *distinct combination* of the
    routinely observable variables once and mapping the scores back onto the cohort, so
    the cost is a few dozen queries rather than one per student.

    Two very different quantities are reported, and they must not be confused:

    ``self_consistency``
        Precision/recall of the threshold against the cohort's own sampled outcome
        column. Because those outcomes were drawn from the very CPDs used to score them,
        this is a **ceiling under the model's own assumptions** -- the best the screen
        could do if the model were exactly right. It is *not* validation, and it will be
        optimistic relative to any real deployment.

    ``precision_ceiling_by_assumed_true_rate``
        An assumption-light bound. For any real base rate ``r``, precision cannot exceed
        ``min(1, r / flag_rate)`` however good the ranking is. With a low real leaving
        rate and a double-digit flag rate, most flagged students will not leave. That is
        not a defect to be tuned away; it is the reason outputs must lead to *offers of
        support* rather than to anything a student can lose.

    Args:
        risk_model: a bundle from :func:`build_model`.
        frame: a cohort from :func:`generate_synthetic_data`.
        thresholds: P(High) cut-offs to evaluate.
        observables: variables treated as available at screening time.
        illustrative_true_rates: hypothetical real leaving rates for the ceiling bound.
        target: outcome variable.

    Returns:
        A serialisable dict of per-threshold flag rates, self-consistency metrics and
        precision ceilings.

    Raises:
        ValueError: if ``frame`` lacks a required column.
    """
    missing = [c for c in (*observables, target) if c not in frame.columns]
    if missing:
        raise ValueError(f"cohort frame is missing required column(s): {missing}")

    combos = frame[list(observables)].drop_duplicates()
    scores: dict[tuple[str, ...], float] = {}
    for row in combos.itertuples(index=False):
        evidence = dict(zip(observables, (str(v) for v in row)))
        scores[tuple(evidence.values())] = infer_dropout_risk(
            risk_model, evidence, target=target
        )["posterior"]["High"]
    LOGGER.info("Scored %d distinct observable profiles for screening burden", len(scores))

    keys = list(zip(*(frame[c].astype(str) for c in observables)))
    p_high = np.array([scores[k] for k in keys], dtype=float)
    actually_high = (frame[target].astype(str) == "High").to_numpy()
    cohort_rate = float(actually_high.mean())

    rows: list[dict[str, Any]] = []
    for threshold in thresholds:
        flagged = p_high >= threshold
        n_flagged = int(flagged.sum())
        flag_rate = n_flagged / len(frame)
        true_positive = int((flagged & actually_high).sum())
        rows.append(
            {
                "threshold": threshold,
                "n_flagged": n_flagged,
                "flag_rate": round(flag_rate, 6),
                "flagged_per_1000_students": round(flag_rate * 1000, 1),
                "self_consistency": {
                    "precision": round(true_positive / n_flagged, 6) if n_flagged else None,
                    "recall": (
                        round(true_positive / int(actually_high.sum()), 6)
                        if actually_high.any()
                        else None
                    ),
                    "false_positives": n_flagged - true_positive,
                    "false_negatives": int((~flagged & actually_high).sum()),
                },
                "precision_ceiling_by_assumed_true_rate": {
                    f"{rate:.0%}": (round(min(1.0, rate / flag_rate), 4) if flag_rate else None)
                    for rate in illustrative_true_rates
                },
            }
        )
        LOGGER.info(
            "threshold %.2f -> flags %.1f%% of the cohort (%d per 1000)",
            threshold,
            flag_rate * 100,
            round(flag_rate * 1000),
        )

    return {
        "observables_used": list(observables),
        "n_distinct_profiles": len(scores),
        "cohort_size": int(len(frame)),
        "cohort_sampled_high_rate": round(cohort_rate, 6),
        "thresholds": rows,
        "warning": (
            "self_consistency metrics are computed against outcomes sampled from the same "
            "CPDs that produced the scores. They quantify internal coherence only and "
            "must never be reported as accuracy, validation or performance."
        ),
        "provenance": risk_model.provenance,
    }



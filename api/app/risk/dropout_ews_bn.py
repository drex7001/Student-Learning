def compare_scenarios(
    risk_model: RiskModel,
    scenarios: Sequence[tuple[str, str, dict[str, str], str]] = SCENARIOS,
    *,
    target: str = TARGET_NODE,
) -> dict[str, Any]:
    """Run the scenario battery and compute within-group contrasts.

    Args:
        risk_model: a bundle from :func:`build_model`.
        scenarios: ``(group, label, evidence, note)`` tuples.
        target: variable to query.

    Returns:
        ``{"results": [...], "contrasts": {group: [...]}, "ranking": [...]}`` -- all
        JSON-serialisable. Contrasts are computed against the first scenario listed in
        each group and report the per-state difference plus the change in ``P(High)``.
    """
    results: list[dict[str, Any]] = []
    for group, label, evidence, note in scenarios:
        posterior = infer_dropout_risk(risk_model, evidence, target=target, label=label)
        posterior["group"] = group
        posterior["note"] = note
        results.append(posterior)
        LOGGER.info(
            "scenario %-26s P(%s=High)=%.4f  argmax=%s",
            label,
            target,
            posterior["posterior"]["High"],
            posterior["highest_state"],
        )

    contrasts: dict[str, list[dict[str, Any]]] = {}
    for group in dict.fromkeys(r["group"] for r in results):
        members = [r for r in results if r["group"] == group]
        reference = members[0]
        contrasts[group] = [
            {
                "reference": reference["label"],
                "comparison": other["label"],
                "difference_by_state": {
                    s: round(other["posterior"][s] - reference["posterior"][s], 6)
                    for s in NODE_STATES[target]
                },
                "delta_p_high": round(other["posterior"]["High"] - reference["posterior"]["High"], 6),
                "relative_change_p_high": (
                    round(
                        (other["posterior"]["High"] - reference["posterior"]["High"])
                        / reference["posterior"]["High"],
                        4,
                    )
                    if reference["posterior"]["High"] > 0
                    else None
                ),
                "argmax_changed": other["highest_state"] != reference["highest_state"],
            }
            for other in members[1:]
        ]

    ranking = [r["label"] for r in sorted(results, key=lambda r: -r["posterior"]["High"])]
    return {
        "target": target,
        "model_variant": risk_model.variant.value,
        "model_fingerprint": risk_model.fingerprint,
        "results": results,
        "contrasts": contrasts,
        "ranking_by_p_high_descending": ranking,
        "provenance": risk_model.provenance,
    }


